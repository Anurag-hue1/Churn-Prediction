import joblib
import json
from pathlib import Path

# 1. Ensure the deployment directory exists
deployment_dir = Path("deployment")
deployment_dir.mkdir(exist_ok=True)

# 2. Locate your trained model and preprocessor 
# (Adjust these paths if your trained files are saved under a different folder like models/)
model_source = Path("models/model.pkl") # or wherever train.py saved it
preprocessor_source = Path("models/preprocessor.pkl") # or generated by preprocess.py

# Fallback check: If they are saved directly in root or outputs
if not model_source.exists():
    # Look in common output directories
    for p in Path(".").glob("**/model*.pkl"):
        model_source = p
        break

if not preprocessor_source.exists():
    for p in Path(".").glob("**/preprocessor*.pkl"):
        preprocessor_source = p
        break

print(f"Found model at: {model_source}")
print(f"Found preprocessor at: {preprocessor_source}")

# 3. Load and re-save them into the deployment folder expected by FastAPI & Pytest
model = joblib.load(model_source)
preprocessor = joblib.load(preprocessor_source)

joblib.dump(model, deployment_dir / "model.pkl")
joblib.dump(preprocessor, deployment_dir / "preprocessor.pkl")

# 4. Create a dummy model_metadata.json if it doesn't exist yet
metadata = {
    "model_type": "RandomForestClassifier",
    "version": "1.0.0",
    "features": []
}
with open(deployment_dir / "model_metadata.json", "w") as f:
    json.dump(metadata, f, indent=4)

print("Successfully exported model bundle to deployment/ directory!")